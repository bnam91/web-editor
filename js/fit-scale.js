/**
 * 내용(contentW × contentH)을 뷰포트(viewportW × viewportH) 안에 넣는 배율(1 = 100%).
 * ★높이가 0 이면 vh/0 = Infinity 라 자동으로 «가로 기준»이 된다 — 기존 두 호출부가 기대던 동작
 *   그대로다. 「내용이 아예 없을 때 무엇을 할 것인가」는 여기가 아니라 호출부가 정한다.
 */
export function fitScale(contentW, contentH, viewportW, viewportH) {
  return Math.min(viewportW / contentW, viewportH / contentH);
}
